function shellQuote(s: string): string {
  return "'" + s.replace(/'/g, "'\\''") + "'"
}

const HARNESS_PLUGIN_SIGNATURE = 'harness-opencode-plugin'

export const PLUGIN_PATH = join(homedir(), '.config', 'opencode', 'plugins', 'harness-status.js')

export const defaultCommand = 'opencode'
export const assignsSessionId = false

export const hookEvents = [
  'session.created',
  'session.updated',
  'session.status',
  'session.idle',
  'tool.execute.before',
  'tool.execute.after',
  'permission.asked',
  'permission.updated',
  'permission.replied'
]

function pluginDir(): string {
  return join(homedir(), '.config', 'opencode', 'plugins')
}

export function makePluginContent(): string {
  return `// ${HARNESS_PLUGIN_SIGNATURE}
// Auto-generated by Harness. Emits status events to /tmp/harness-status.
import { appendFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const STATUS_DIR = '/tmp/harness-status'

// opencode treats each top-level binding it finds as a plugin factory, so this file defines only HarnessStatus.
export const HarnessStatus = async ({ client }) => {
  const terminalId = process.env.HARNESS_TERMINAL_ID || process.env.CLAUDE_HARNESS_ID
  if (!terminalId) return {}
  const file = join(STATUS_DIR, terminalId + '.ndjson')
  const parents = new Map()
  const busy = new Set()
  const rootOf = (id) => {
    let cur = id
    const seen = new Set()
    while (parents.has(cur) && !seen.has(cur)) {
      seen.add(cur)
      cur = parents.get(cur)
    }
    return cur
  }
  const emit = (event, payload) => {
    try {
      mkdirSync(STATUS_DIR, { recursive: true })
      appendFileSync(file, JSON.stringify({ event, ts: Math.floor(Date.now() / 1000), payload }) + '\\n')
    } catch {}
  }
  const lastAssistantMessage = async (id) => {
    try {
      const res = await client.session.messages({ path: { id }, query: { limit: 20 } })
      const list = Array.isArray(res?.data) ? res.data : []
      for (let i = list.length - 1; i >= 0; i--) {
        if (list[i]?.info?.role !== 'assistant') continue
        const text = (list[i].parts || [])
          .filter((p) => p?.type === 'text' && !p.synthetic)
          .map((p) => p.text)
          .join('\\n')
          .trim()
        return text || null
      }
    } catch {}
    return null
  }
  return {
    event: async ({ event }) => {
      try {
        const p = event?.properties || {}
        switch (event?.type) {
          case 'session.created':
          case 'session.updated':
            if (p.info?.id && p.info.parentID) parents.set(p.info.id, p.info.parentID)
            break
          case 'session.status': {
            const root = rootOf(p.sessionID)
            if (p.status?.type === 'busy') {
              if (!busy.has(root)) {
                busy.add(root)
                emit('UserPromptSubmit', { session_id: root })
              }
            } else if (p.status?.type === 'idle' && root === p.sessionID) {
              busy.delete(root)
            }
            break
          }
          case 'session.idle': {
            if (!p.sessionID || parents.has(p.sessionID)) break
            busy.delete(p.sessionID)
            emit('Stop', { session_id: p.sessionID, last_assistant_message: await lastAssistantMessage(p.sessionID) })
            break
          }
          case 'permission.asked':
            emit('Notification', {
              notification_type: 'permission_prompt',
              session_id: rootOf(p.sessionID),
              tool_name: p.permission,
              tool_input: { patterns: p.patterns, ...(p.metadata || {}) }
            })
            break
          case 'permission.updated':
            emit('Notification', {
              notification_type: 'permission_prompt',
              session_id: rootOf(p.sessionID),
              tool_name: p.type,
              tool_input: { pattern: p.pattern, ...(p.metadata || {}) }
            })
            break
          case 'permission.replied':
            emit('UserPromptSubmit', { session_id: rootOf(p.sessionID) })
            break
        }
      } catch {}
    },
    'tool.execute.before': async (input, output) => {
      try {
        emit('PreToolUse', { session_id: rootOf(input?.sessionID), tool_name: input?.tool, tool_input: output?.args ?? {} })
      } catch {}
    },
    'tool.execute.after': async (input) => {
      try {
        emit('PostToolUse', { session_id: rootOf(input?.sessionID), tool_name: input?.tool, tool_input: input?.args ?? {} })
      } catch {}
    }
  }
}
`
}

export function hooksInstalled(): boolean {
  try {
    if (!existsSync(PLUGIN_PATH)) return false
    const content = readFileSync(PLUGIN_PATH, 'utf-8')
    return content.includes(HARNESS_PLUGIN_SIGNATURE)
  } catch {
    return false
  }
}

export function installHooks(): void {
  const dir = pluginDir()
  log('hooks', `installing Opencode plugin into ${PLUGIN_PATH}`)
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true })
  writeFileSync(PLUGIN_PATH, makePluginContent())
}

export function uninstallHooks(): void {
  if (!existsSync(PLUGIN_PATH)) return
  try {
    const content = readFileSync(PLUGIN_PATH, 'utf-8')
    if (content.includes(HARNESS_PLUGIN_SIGNATURE)) {
      unlinkSync(PLUGIN_PATH)
      log('hooks', `uninstalled Opencode plugin from ${PLUGIN_PATH}`)
    }
  } catch {
    // ignore
  }
}

export function stripHooksFromWorktree(_worktreePath: string): boolean {
  // Opencode has no legacy per-worktree plugin path.
  return false
}

export function sessionFileExists(_cwd: string, sessionId: string): boolean {
  try {
    execSync(`opencode export ${sessionId}`, { stdio: 'pipe', timeout: 5000 })
    return true
  } catch {
    return false
  }
}

export function latestSessionId(_cwd: string): string | null {
  try {
    const output = execSync('opencode session list --format json --max-count 1', {
      stdio: 'pipe',
      timeout: 5000,
      encoding: 'utf-8'
    })
    const parsed = JSON.parse(output) as Array<{ id?: string }>
    if (Array.isArray(parsed) && parsed.length > 0 && typeof parsed[0].id === 'string') {
      return parsed[0].id
    }
    return null
  } catch {
    return null
  }
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === 'object' && !Array.isArray(value)
}

export const OPENCODE_STEP_AGENT = 'harness-step'

export function opencodeStepPermission(level: PermissionLevel, bashAllow: string[]): Record<string, unknown> {
  if (level === 'full') return { '*': 'allow' }
  const restricted = {
    '*': 'deny',
    read: 'allow',
    glob: 'allow',
    grep: 'allow',
    list: 'allow',
    'harness-control_*': 'allow'
  }
  if (level === 'read-only') {
    return {
      ...restricted,
      edit: { '*': 'deny', [RUN_FOLDER_GLOB]: 'allow' },
      bash: 'deny',
      external_directory: 'deny',
      doom_loop: 'deny'
    }
  }
  return {
    ...restricted,
    edit: 'allow',
    bash: {
      '*': 'deny',
      ...Object.fromEntries(bashAllow.flatMap((p) => [[p, 'allow'], [`${p} *`, 'allow']]))
    },
    external_directory: 'deny',
    doom_loop: 'deny'
  }
}

export function opencodeStepAgent(
  level: PermissionLevel,
  bashAllow: string[],
  model?: string | null
): Record<string, unknown> {
  return {
    mode: 'primary',
    description: 'Tatsu workflow step',
    tools: { task: false },
    permission: opencodeStepPermission(level, bashAllow),
    ...(model ? { model } : {})
  }
}

function stepAgentApplies(opts: AgentSpawnOpts): boolean {
  return !!opts.permissionLevel && !opts.command.includes('--agent')
}

export function buildOpencodeConfig(
  opts: AgentSpawnOpts,
  base: Record<string, unknown>
): Record<string, unknown> {
  const config: Record<string, unknown> = { ...base }
  const server = opts.mcpServer
  if (server) {
    config.mcp = {
      ...(isPlainObject(base.mcp) ? base.mcp : {}),
      'harness-control': {
        type: 'local',
        command: [server.command, ...server.args],
        environment: server.env,
        enabled: true
      }
    }
  }
  if (opts.permissionLevel && stepAgentApplies(opts)) {
    config.agent = {
      ...(isPlainObject(base.agent) ? base.agent : {}),
      [OPENCODE_STEP_AGENT]: opencodeStepAgent(opts.permissionLevel, opts.bashAllow ?? [], opts.model)
    }
  }
  return config
}

export function spawnEnv(
  opts: AgentSpawnOpts,
  baseEnv: Record<string, string>,
  inheritedEnv: Readonly<Record<string, string | undefined>>
): Record<string, string> {
  const raw = baseEnv.OPENCODE_CONFIG_CONTENT ?? inheritedEnv.OPENCODE_CONFIG_CONTENT
  let base: Record<string, unknown> = {}
  if (raw !== undefined) {
    let parsed: unknown
    try {
      parsed = JSON.parse(raw)
    } catch {
      parsed = undefined
    }
    if (isPlainObject(parsed)) base = parsed
    else log('mcp', 'ignoring non-object OPENCODE_CONFIG_CONTENT')
  }
  const config = buildOpencodeConfig(opts, base)
  if (raw === undefined && JSON.stringify(config) === JSON.stringify(base)) return {}
  return { OPENCODE_CONFIG_CONTENT: JSON.stringify(config) }
}

export function buildSpawnArgs(opts: AgentSpawnOpts): string {
  let cmd = opts.command

  if (opts.permissionLevel) {
    if (stepAgentApplies(opts)) cmd += ` --agent ${OPENCODE_STEP_AGENT}`
    else log('agent-spawn', 'opencode command already sets --agent; permissionLevel not applied')
  }

  if (opts.model && !opts.command.includes('--model') && !opts.command.includes('-m ')) {
    cmd += ` --model ${shellQuote(opts.model)}`
  }

  if (opts.sessionId) {
    const exists = sessionFileExists(opts.cwd, opts.sessionId)
    if (exists) {
      cmd += ` --session ${shellQuote(opts.sessionId)}`
      if (opts.initialPrompt) {
        cmd += ` --prompt ${shellQuote(opts.initialPrompt)}`
      }
      return cmd
    }
  }

  if (opts.initialPrompt) {
    cmd += ` --prompt ${shellQuote(opts.initialPrompt)}`
  }

  return cmd
}

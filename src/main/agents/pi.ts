export function sessionFileExists(_cwd: string, sessionId: string): boolean {
  try {
    // Pi hook events always provide absolute session file paths.
    if (sessionId.startsWith('/') || sessionId.startsWith('~')) {
      const resolved = sessionId.startsWith('~') ? join(homedir(), sessionId.slice(1)) : sessionId
      return existsSync(resolved)
    }
    return false
  } catch {
    return false
  }
}

export function latestSessionId(cwd: string): string | null {
  const now = Date.now()
  const cached = latestSessionCache.get(cwd)
  if (cached && cached.expiresAt > now) return cached.value

  let bestId: string | null = null
  try {
    const sessionsDir = join(homedir(), '.pi', 'agent', 'sessions')
    if (!existsSync(sessionsDir)) {
      latestSessionCache.set(cwd, { value: null, expiresAt: now + LATEST_SESSION_CACHE_TTL_MS })
      return null
    }
    // Pi stores sessions in subdirs named after the cwd: --path--/timestamp_uuid.jsonl
    const cwdSlug = '--' + cwd.replace(/^\//, '').split('/').join('--') + '--'
    const dirs = readdirSync(sessionsDir)
    let bestMtime = -Infinity
    for (const entry of dirs) {
      if (entry !== cwdSlug) continue
      const fullPath = join(sessionsDir, entry)
      try {
        const st = statSync(fullPath)
        if (st.isDirectory()) {
          const subEntries = readdirSync(fullPath)
          for (const sub of subEntries) {
            if (sub.endsWith('.jsonl')) {
              const fp = join(fullPath, sub)
              const mtime = statSync(fp).mtimeMs
              if (mtime > bestMtime) {
                bestMtime = mtime
                bestId = fp
              }
            }
          }
        } else if (entry.endsWith('.jsonl')) {
          if (st.mtimeMs > bestMtime) {
            bestMtime = st.mtimeMs
            bestId = fullPath
          }
        }
      } catch { /* skip */ }
    }
    latestSessionCache.set(cwd, { value: bestId, expiresAt: now + LATEST_SESSION_CACHE_TTL_MS })
    return bestId
  } catch {
    latestSessionCache.set(cwd, { value: null, expiresAt: now + LATEST_SESSION_CACHE_TTL_MS })
    return null
  }
}

export function buildSpawnArgs(opts: AgentSpawnOpts): string {
  let cmd = opts.command

  if (opts.model && !opts.command.includes('--model')) {
    cmd += ` --model ${shellQuote(opts.model)}`
  }

  if (opts.sessionName && !opts.command.includes('--name')) {
    cmd += ` --name ${shellQuote(opts.sessionName)}`
  }

  if (opts.sessionId && !opts.command.includes('--session')) {
    const exists = sessionFileExists(opts.cwd, opts.sessionId)
    if (exists) {
      cmd += ` --session ${shellQuote(opts.sessionId)}`
      if (opts.initialPrompt) {
        cmd += ` ${shellQuote(opts.initialPrompt)}`
      }
      return cmd
    }
  }

  if (opts.initialPrompt) {
    cmd += ` ${shellQuote(opts.initialPrompt)}`
  }

  return cmd
}
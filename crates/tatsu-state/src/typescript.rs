pub fn export_typescript(mut types: Types) -> Result<String, specta_typescript::Error> {
    let opaque = Opaque {
        number: specta_typescript::Number::<()>::definition(&mut Types::default()),
        unknown: specta_typescript::Unknown::<()>::definition(&mut Types::default()),
        json_value: serde_json::Value::definition(&mut types),
    };
    let json_value_path = match &opaque.json_value {
        DataType::Reference(Reference::Named(reference)) => types
            .get(reference)
            .map(|ndt| (ndt.name.clone(), ndt.module_path.clone())),
        _ => None,
    };
    types.iter_mut(|ndt| {
        if json_value_path
            .as_ref()
            .is_some_and(|(name, module)| *name == ndt.name && *module == ndt.module_path)
        {
            ndt.ty = None;
        } else if let Some(ty) = ndt.ty.as_mut() {
            to_serialized_shape(ty, &opaque);
        }
    });
    Typescript::default()
        .header(HEADER)
        .export(&types, specta_serde::Format)
}

struct Opaque {
    number: DataType,
    unknown: DataType,
    json_value: DataType,
}

// The hand-written TS types describe what Rust sends, so serde defaults (which only
// relax deserialization) must not turn fields optional, an `Option` skipped when `None`
// is never `null`, an adjacently tagged `Option` payload is always sent, JSON numbers are plain `number` (Rust never emits NaN/Infinity and
// 64-bit values travel as JS numbers), and raw JSON values are `unknown`.
fn to_serialized_shape(ty: &mut DataType, opaque: &Opaque) {
    match ty {
        DataType::Primitive(
            Primitive::f16
            | Primitive::f32
            | Primitive::f64
            | Primitive::f128
            | Primitive::i64
            | Primitive::u64
            | Primitive::i128
            | Primitive::u128
            | Primitive::isize
            | Primitive::usize,
        ) => *ty = opaque.number.clone(),
        DataType::Primitive(_) | DataType::Generic(_) => {}
        DataType::Struct(s) => {
            remove_serde_defaults(&mut s.attributes);
            fields_to_serialized_shape(&mut s.fields, opaque);
        }
        DataType::Enum(e) => {
            for (_, variant) in &mut e.variants {
                fields_to_serialized_shape(&mut variant.fields, opaque);
            }
        }
        DataType::List(list) => to_serialized_shape(&mut list.ty, opaque),
        DataType::Map(map) => {
            to_serialized_shape(map.key_ty_mut(), opaque);
            to_serialized_shape(map.value_ty_mut(), opaque);
        }
        DataType::Tuple(tuple) => {
            for element in &mut tuple.elements {
                to_serialized_shape(element, opaque);
            }
        }
        DataType::Intersection(parts) => {
            for part in parts {
                to_serialized_shape(part, opaque);
            }
        }
        DataType::Nullable(inner) => to_serialized_shape(inner, opaque),
        DataType::Reference(reference) if is_same_reference(reference, &opaque.json_value) => {
            *ty = opaque.unknown.clone()
        }
        DataType::Reference(Reference::Named(reference)) => match &mut reference.inner {
            NamedReferenceType::Inline { dt, .. } => to_serialized_shape(dt, opaque),
            NamedReferenceType::Reference { generics, .. } => {
                for (_, generic) in generics {
                    to_serialized_shape(generic, opaque);
                }
            }
            NamedReferenceType::Recursive(_) => {}
        },
        DataType::Reference(_) => {}
    }
}

fn fields_to_serialized_shape(fields: &mut Fields, opaque: &Opaque) {
    let each: Box<dyn Iterator<Item = &mut Field>> = match fields {
        Fields::Unit => return,
        Fields::Unnamed(unnamed) => Box::new(unnamed.fields.iter_mut()),
        Fields::Named(named) => Box::new(named.fields.iter_mut().map(|(_, field)| field)),
    };
    for field in each {
        remove_serde_defaults(&mut field.attributes);
        field.attributes.remove(SPECTA_NULLABLE_FIELD);
        if field
            .attributes
            .get_named_as::<String>(SERDE_SKIP_SERIALIZING_IF)
            .is_some_and(|predicate| predicate == "Option::is_none")
            && let Some(DataType::Nullable(inner)) = field.ty.take()
        {
            field.ty = Some(*inner);
        }
        if let Some(ty) = field.ty.as_mut() {
            to_serialized_shape(ty, opaque);
        }
    }
}

fn is_same_reference(reference: &Reference, other: &DataType) -> bool {
    matches!(other, DataType::Reference(other) if reference.ty_eq(other))
}

fn remove_serde_defaults(attributes: &mut specta::datatype::Attributes) {
    for key in SERDE_DEFAULT_ATTRIBUTES {
        attributes.remove(key);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exports_the_serialized_snooze_shape() {
        let ts = export_typescript(
            Types::default()
                .register::<SnoozeState>()
                .register::<SnoozeEvent>(),
        )
        .unwrap();
        assert!(ts.contains("\tsnoozedAt: number,\n"), "{ts}");
        assert!(ts.contains("\twakeAt: number,\n"), "{ts}");
        assert!(ts.contains("\tbyPath: {"), "{ts}");
        assert!(!ts.contains("| null"), "{ts}");
    }

    #[test]
    fn exports_64_bit_integers_as_number() {
        #[derive(Type)]
        #[allow(dead_code)]
        struct Clock {
            at: i64,
            bytes: u64,
        }

        let ts = export_typescript(Types::default().register::<Clock>()).unwrap();
        assert!(ts.contains("\tat: number,\n"), "{ts}");
        assert!(ts.contains("\tbytes: number,\n"), "{ts}");
    }

    #[test]
    fn exports_skipped_options_as_optional_without_null_and_json_values_as_unknown() {
        #[derive(Type, serde::Serialize)]
        #[allow(dead_code)]
        struct Probe {
            #[serde(skip_serializing_if = "Option::is_none")]
            label: Option<String>,
            size: Option<u64>,
            raw: serde_json::Value,
            map: serde_json::Map<String, serde_json::Value>,
        }

        let ts = export_typescript(Types::default().register::<Probe>()).unwrap();
        assert!(ts.contains("\tlabel?: string,\n"), "{ts}");
        assert!(ts.contains("\tsize: number | null,\n"), "{ts}");
        assert!(ts.contains("\traw: unknown,\n"), "{ts}");
        assert!(
            ts.contains("\tmap: { [key in string]: unknown },\n"),
            "{ts}"
        );
        assert!(!ts.contains("export type Value"), "{ts}");
    }

    #[test]
    fn exports_a_skipped_double_option_as_optional_and_nullable() {
        #[derive(Type, serde::Serialize)]
        #[allow(dead_code)]
        struct Probe {
            #[serde(skip_serializing_if = "Option::is_none")]
            milestone: Option<Option<String>>,
        }

        let ts = export_typescript(Types::default().register::<Probe>()).unwrap();
        assert!(ts.contains("\tmilestone?: string | null,\n"), "{ts}");
    }

    #[test]
    fn exports_an_adjacently_tagged_option_payload_as_required_and_nullable() {
        #[derive(Type, serde::Serialize)]
        #[serde(tag = "type", content = "payload")]
        #[allow(dead_code)]
        enum Probe {
            #[serde(rename = "login")]
            Login(Option<String>),
        }

        let ts = export_typescript(Types::default().register::<Probe>()).unwrap();
        assert!(
            ts.contains(r#"{ type: "login"; payload: string | null }"#),
            "{ts}"
        );
    }
}

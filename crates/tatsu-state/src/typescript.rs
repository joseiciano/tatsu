use specta::{
    Type, Types,
    datatype::{DataType, Field, Fields, NamedReferenceType, Primitive, Reference},
};
use specta_typescript::Typescript;

use crate::slices::snooze::{SnoozeEntry, SnoozeEvent, SnoozeState};

const HEADER: &str = "// Generated by `pnpm gen:wire-types` from crates/tatsu-state. Do not edit.";
const SERDE_DEFAULT_ATTRIBUTES: [&str; 2] = ["serde:container:default", "serde:field:default"];

pub fn wire_types() -> Types {
    Types::default()
        .register::<SnoozeEntry>()
        .register::<SnoozeState>()
        .register::<SnoozeEvent>()
}

pub fn export_typescript() -> Result<String, specta_typescript::Error> {
    render(wire_types())
}

fn render(mut types: Types) -> Result<String, specta_typescript::Error> {
    let number = specta_typescript::Number::<()>::definition(&mut Types::default());
    types.iter_mut(|ndt| {
        if let Some(ty) = ndt.ty.as_mut() {
            to_serialized_shape(ty, &number);
        }
    });
    Typescript::default()
        .header(HEADER)
        .export(&types, specta_serde::Format)
}

// The hand-written TS types describe what Rust sends, so serde defaults (which only
// relax deserialization) must not turn fields optional, and JSON numbers are plain
// `number`: Rust never emits NaN/Infinity and 64-bit values travel as JS numbers.
fn to_serialized_shape(ty: &mut DataType, number: &DataType) {
    match ty {
        DataType::Primitive(
            Primitive::f16
            | Primitive::f32
            | Primitive::f64
            | Primitive::f128
            | Primitive::i64
            | Primitive::u64
            | Primitive::i128
            | Primitive::u128
            | Primitive::isize
            | Primitive::usize,
        ) => *ty = number.clone(),
        DataType::Primitive(_) | DataType::Generic(_) => {}
        DataType::Struct(s) => {
            remove_serde_defaults(&mut s.attributes);
            fields_to_serialized_shape(&mut s.fields, number);
        }
        DataType::Enum(e) => {
            for (_, variant) in &mut e.variants {
                fields_to_serialized_shape(&mut variant.fields, number);
            }
        }
        DataType::List(list) => to_serialized_shape(&mut list.ty, number),
        DataType::Map(map) => {
            to_serialized_shape(map.key_ty_mut(), number);
            to_serialized_shape(map.value_ty_mut(), number);
        }
        DataType::Tuple(tuple) => {
            for element in &mut tuple.elements {
                to_serialized_shape(element, number);
            }
        }
        DataType::Intersection(parts) => {
            for part in parts {
                to_serialized_shape(part, number);
            }
        }
        DataType::Nullable(inner) => to_serialized_shape(inner, number),
        DataType::Reference(Reference::Named(reference)) => match &mut reference.inner {
            NamedReferenceType::Inline { dt, .. } => to_serialized_shape(dt, number),
            NamedReferenceType::Reference { generics, .. } => {
                for (_, generic) in generics {
                    to_serialized_shape(generic, number);
                }
            }
            NamedReferenceType::Recursive(_) => {}
        },
        DataType::Reference(_) => {}
    }
}

fn fields_to_serialized_shape(fields: &mut Fields, number: &DataType) {
    let each: Box<dyn Iterator<Item = &mut Field>> = match fields {
        Fields::Unit => return,
        Fields::Unnamed(unnamed) => Box::new(unnamed.fields.iter_mut()),
        Fields::Named(named) => Box::new(named.fields.iter_mut().map(|(_, field)| field)),
    };
    for field in each {
        remove_serde_defaults(&mut field.attributes);
        if let Some(ty) = field.ty.as_mut() {
            to_serialized_shape(ty, number);
        }
    }
}

fn remove_serde_defaults(attributes: &mut specta::datatype::Attributes) {
    for key in SERDE_DEFAULT_ATTRIBUTES {
        attributes.remove(key);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exports_the_serialized_snooze_shape() {
        let ts = export_typescript().unwrap();
        assert!(ts.contains("\tsnoozedAt: number,\n"), "{ts}");
        assert!(ts.contains("\twakeAt: number,\n"), "{ts}");
        assert!(ts.contains("\tbyPath: {"), "{ts}");
        assert!(!ts.contains("| null"), "{ts}");
    }

    #[test]
    fn exports_64_bit_integers_as_number() {
        #[derive(Type)]
        #[allow(dead_code)]
        struct Clock {
            at: i64,
            bytes: u64,
        }

        let ts = render(Types::default().register::<Clock>()).unwrap();
        assert!(ts.contains("\tat: number,\n"), "{ts}");
        assert!(ts.contains("\tbytes: number,\n"), "{ts}");
    }
}
